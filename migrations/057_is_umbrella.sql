-- Явный флаг "это зонтик" (задача 2026-08-13) — раньше "зонтик" был
-- ЧИСТО производным понятием ("ЖК, у которого есть хотя бы один дом",
-- см. docs/entity_resolution_plan.md и комментарии в umbrellas.html/
-- complex_detail.html) — намеренное решение "не нужен отдельный флаг".
-- Живой фидбек 2026-08-13 изменил это: "если я хочу сделать жк зонтиком
-- — надо просто по нажатию... а если я не добавил в него другие дом —
-- потом добавлю когда-нибудь" — то есть нужно фиксировать НАМЕРЕНИЕ
-- ("это зонтик") ДО того, как в него добавлен хоть один дом, а чистого
-- EXISTS(дети) для этого недостаточно (ноль детей = не отличить от
-- обычного ЖК). is_umbrella — намерение; фактическое множество детей
-- (parent_complex_id) — как и раньше, отдельная, независимая вещь;
-- "группа домов"/список на /admin/umbrellas теперь показывает ЖК с
-- is_umbrella=TRUE ИЛИ с реальными детьми (кто-то мог стать домом через
-- "Добавить дом к ЖК" на СВОЕЙ странице, не через явную отметку зонтика
-- на родителе — оба пути остаются рабочими).
ALTER TABLE complexes ADD COLUMN IF NOT EXISTS is_umbrella BOOLEAN NOT NULL DEFAULT FALSE;
