DDL = """
CREATE TABLE IF NOT EXISTS demolition_houses (
  id SERIAL PRIMARY KEY,
  address TEXT NOT NULL,
  district TEXT,
  apartments INT,
  demolish_year INT,
  year_built INT,
  wear_pct NUMERIC(5,1),
  lat DOUBLE PRECISION,
  lon DOUBLE PRECISION,
  geocoded_at TIMESTAMPTZ,
  source TEXT DEFAULT 'gov.kz перечень 18.06.2026',
  created_at TIMESTAMPTZ DEFAULT now(),
  UNIQUE (address, demolish_year)
);
"""

def psql(sql: str) -> str:
    r = subprocess.run(["sudo", "-u", "postgres", "psql", "-d", "krisha_bot", "-t", "-A", "-c", sql],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(r.stderr.strip()[:300])
    return r.stdout.strip()

if __name__ == "__main__":
    psql(DDL)
    psql("TRUNCATE demolition_houses RESTART IDENTITY")
    n = 0
    for addr, dist, apt, yr, yb, wear in H:
        wear_s = f"'{wear}'" if wear else "NULL"
        yb_s = f"'{yb}'" if yb else "NULL"
        psql(f"INSERT INTO demolition_houses (address, district, apartments, demolish_year, year_built, wear_pct) "
             f"VALUES ('{addr.replace(chr(39), chr(39)*2)}', '{dist}', {apt}, {yr}, {yb_s}, {wear_s})")
        n += 1
    print(f"Вставлено домов: {n}")
    print(psql("SELECT demolish_year, COUNT(*), SUM(apartments) FROM demolition_houses GROUP BY 1 ORDER BY 1"))
